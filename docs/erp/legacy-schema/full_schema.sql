DECLARE VARIABLE ZUB NUMERIC (15,2);
DECLARE VARIABLE AB NUMERIC (15,2);
DECLARE VARIABLE AB2 NUMERIC (15,2);

BEGIN
 SELECT SUM(GELIEFERT) FROM BELEGPOS,BELEG
  WHERE (BELEG.BELEGART = 205
  OR BELEG.BELEGART = 405)
  AND BELEGPOS.SOID = BELEG.OID
  AND BELEGPOS.ARTOID = :AOID
  INTO :ZUB;

 SELECT SUM(STCK) FROM BELEGPOS,BELEG
  WHERE (BELEG.BELEGART = 203
  OR BELEG.BELEGART = 206 
  OR BELEG.BELEGART = 403)
  AND BELEGPOS.SOID = BELEG.OID
  AND ARTOID = :AOID
  INTO :AB;

 SELECT SUM(STCK) FROM BELEGPOS,BELEG
  WHERE (BELEG.BELEGART = 200
  OR BELEG.BELEGART = 300 
  OR BELEG.BELEGART = 400)
  AND BELEGPOS.SOID = BELEG.OID
  AND ARTOID = :AOID
  INTO :AB2;

  IF (:ZUB IS NULL) THEN ZUB = 0; ELSE ZUB = :ZUB;

  IF (:AB IS NULL) THEN AB = 0; ELSE AB = :AB;

  IF (:AB2 IS NULL) THEN AB2 = 0; ELSE AB2 = :AB2;

  BESTAND = ZUB  - AB - AB2;
SUSPEND;
END ^
SET TERM ; ^
COMMIT WORK ;
SET AUTODDL ON;
SET TERM ^ ;

/* Triggers only will work for SQL triggers */
CREATE TRIGGER T_FAELLIG_BI FOR BELEG 
ACTIVE BEFORE INSERT POSITION 0 
AS

DECLARE VARIABLE TAGE INTEGER;
DECLARE Variable ZAHLUNG NUMERIC(15,2);

BEGIN
  /*Fälligkeit von Rechnung*/
  IF (BELEG.BELEGART <> 104) THEN
  BEGIN
  EXECUTE PROCEDURE P_RECHNUNGFAELLIG BELEG.ZKONDI
  RETURNING_VALUES :TAGE;
  BELEG.FAELLIG = BELEG.BELEGDATUM + :TAGE;
  END

  /*Offener Rechnungsbetrag nur bei Belegart Rechnung*/
  EXECUTE PROCEDURE P_BELEGOFFEN BELEG.OID
   RETURNING_VALUES :ZAHLUNG;

  IF (BELEG.BELEGART = 3) THEN BELEG.OFFEN = BELEG.BRUTTO - :ZAHLUNG;
END ^

